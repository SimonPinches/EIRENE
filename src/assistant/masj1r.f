C*DK MASJ1R
      SUBROUTINE EIRENE_MASJ1R (A,I,B)
      USE EIRMOD_PRECISION
      USE EIRMOD_COMPRT, ONLY: IUNOUT
      IMPLICIT NONE
      CHARACTER(16), INTENT(IN) :: A
      REAL(DP), INTENT(IN) :: B
      INTEGER, INTENT(IN) :: I
      REAL(DP) :: FI
      IF (I.LT.1000000) THEN
        WRITE (IUNOUT,60) A,I,B
      ELSEIF (I.LT.100000000) THEN
        WRITE (IUNOUT,70) A,I,B
      ELSE
        FI=I
        WRITE (IUNOUT,80) A,FI,B
      ENDIF
      
   60 FORMAT (1X,A16,3X,I6,3X,1PE12.4)
   70 FORMAT (1X,A16,1X,I8,3X,1PE12.4)
   80 FORMAT (1X,A16,3X,1PE12.4,3X,1PE12.4)
      RETURN
      END SUBROUTINE EIRENE_MASJ1R
