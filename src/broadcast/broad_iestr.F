

      SUBROUTINE EIRENE_BROAD_IESTR(IESTR)
      USE EIRMOD_MPI
      IMPLICIT NONE

      INTEGER, INTENT(IN) :: IESTR
      INTEGER :: IER
      EXTERNAL :: EIRENE_CHECK_EXIT
#if ( defined(USE_MPI) && !defined(GFORTRAN) && !defined(CRAY) )
      EXTERNAL :: MPI_BCAST
#endif

      CALL EIRENE_CHECK_EXIT
      CALL MPI_BARRIER (MPI_COMM_WORLD,IER)
      CALL MPI_BCAST (IESTR,1,MPI_INTEGER,0,MPI_COMM_WORLD,IER)
      CALL MPI_BARRIER (MPI_COMM_WORLD,IER)

      RETURN
      END SUBROUTINE EIRENE_BROAD_IESTR
