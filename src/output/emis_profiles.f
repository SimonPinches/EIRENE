      TXTTAL(IAD1,NTALA) =TRIM(LINE_NAME) // ', ' //
     .                    TRIM(LINE_NAME) // ' SOURCE RATE '
      TXTSPC(IAD1,NTALA) ='GROUNDSTATE             '
      TXTUNT(IAD1,NTALA) ='PHOTONS/S/CM**3         '

