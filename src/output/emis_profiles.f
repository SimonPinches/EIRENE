      SUBROUTINE EIRENE_PREPARE_LINE
C
      INTEGER, SAVE :: IFIRST = 0

      REAL(DP) :: FP1(6), FP2(6)
      REAL(DP) :: RC1MIN, RC1MAX, RC2MIN, RC2MAX
      INTEGER :: JFEX1MN, JFEX1MX, JFEX2MN, JFEX2MX, IR

      CHARACTER(8) :: FILNAM
      CHARACTER(4) :: H123
      CHARACTER(9) :: REAC
      CHARACTER(3) :: CRC
      CHARACTER(LEN(REAC)) :: REAC_A, REAC_B, REAC_M, REAC_I2,
     .                         REAC_I3, REAC_N

      IF (IFIRST == 0) THEN
         FAC = 0._DP
C  RADIATIVE TRANSITION RATES (1/S)
C  BALMER ALPHA
         FAC(3,2) = 4.410E7
C  BALMER BETA
         FAC(4,2) = 8.419E6
C  BALMER GAMMA
         FAC(5,2) = 2.530E6
C  BALMER DELTA
         FAC(6,2) = 9.732E5
C
C  LYMAN ALPHA
         FAC(2,1) = 4.699E8
C  LYMAN BETA
         FAC(3,1) = 5.575E7
C  LYMAN GAMMA
         FAC(4,1) = 1.278E7
C  LYMAN DELTA
         FAC(5,1) = 4.125E6
C  LYMAN EPSILON
         FAC(6,1) = 1.644E6
C
C  PASCHEN ALPHA
         FAC(4,3) = 8.986E6
C  PASCHEN BETA
         FAC(5,3) = 2.201E6
C  PASCHEN GAMMA
         FAC(6,3) = 7.783E5

         NUM_LINES_AVAIL = MAX (BA_ALPHA, BA_BETA, BA_GAMMA, BA_DELTA,
     .                          LY_ALPHA, LY_BETA)
         ALLOCATE (LINES(NUM_LINES_AVAIL))
         ALLOCATE (LREAD_LINE(NUM_LINES_AVAIL))
         LINES = 0
         LREAD_LINE = .TRUE.
         LINES_DEF = 0

         IFIRST = 1
      END IF

C  DECIDE WHICH LINE IS TO BE USED
      IF (ABS(ENER-12.089_DP)/12.089_DP <= EPS5) THEN

        LINENO = LY_BETA
        LINE_NAME = 'LY-BETA  '

        L1 = 3
        L2 = 1
        
        IF (LINES(LINENO) == 0) THEN

          LINES_DEF = LINES_DEF + 1
          LINES(LINENO) = LINES_DEF

          REAC_A='2.1.5a   '
          REAC_B='2.1.8a   '
          REAC_M='2.2.5a   '
          REAC_I2='2.2.14a  '
          REAC_I3='2.2.15a  '
          REAC_N='7.2a     '

        END IF

      ELSEIF (ABS(ENER-10.2375_DP)/10.2375_DP <= EPS5) THEN

        LINENO = LY_ALPHA
        LINE_NAME = 'LY-ALPHA '

        L1 = 2
        L2 = 1
        
        IF (LINES(LINENO) == 0) THEN

          LINES_DEF = LINES_DEF + 1
          LINES(LINENO) = LINES_DEF

          REAC_A='2.1.5b   '
          REAC_B='2.1.8b   '
          REAC_M='2.2.5b   '
          REAC_I2='2.2.14b  '
          REAC_I3='2.2.15b  '
          REAC_N='7.2b     '

        END IF

      ELSEIF (ABS(ENER-3.0222_DP)/3.0222_DP <= EPS5) THEN

        LINENO = BA_DELTA
        LINE_NAME = 'BA-DELTA '

        L1 = 6
        L2 = 2

        IF (LINES(LINENO) == 0) THEN

          LINES_DEF = LINES_DEF + 1
          LINES(LINENO) = LINES_DEF

          REAC_A='2.1.5e   '
          REAC_B='2.1.8e   '
          REAC_M='2.2.5e   '
          REAC_I2='2.2.14e  '
          REAC_I3='2.2.15e  '
          REAC_N='7.2e     '

        END IF

      ELSEIF (ABS(ENER-2.8560_DP)/2.8560_DP <= EPS5) THEN

        LINENO = BA_GAMMA
        LINE_NAME = 'BA-GAMMA '

        L1 = 5
        L2 = 2

        IF (LINES(LINENO) == 0) THEN

          LINES_DEF = LINES_DEF + 1
          LINES(LINENO) = LINES_DEF

          REAC_A='2.1.5d   '
          REAC_B='2.1.8d   '
          REAC_M='2.2.5d   '
          REAC_I2='2.2.14d  '
          REAC_I3='2.2.15d  '
          REAC_N='7.2d     '
          
        END IF

      ELSEIF (ABS(ENER-2.5500_DP)/2.5500_DP <= EPS5) THEN

        LINENO = BA_BETA
        LINE_NAME = 'BA-BETA  '

        L1 = 4
        L2 = 2

        IF (LINES(LINENO) == 0) THEN

          LINES_DEF = LINES_DEF + 1
          LINES(LINENO) = LINES_DEF

          REAC_A='2.1.5c   '
          REAC_B='2.1.8c   '
          REAC_M='2.2.5c   '
          REAC_I2='2.2.14c  '
          REAC_I3='2.2.15c  '
          REAC_N='7.2c     '
          
        END IF

      ELSEIF (ABS(ENER-1.8889_DP)/1.8889_DP <= EPS5) THEN

        LINENO = BA_ALPHA
        LINE_NAME = 'BA-ALPHA '

        L1 = 3
        L2 = 2

        IF (LINES(LINENO) == 0) THEN

          LINES_DEF = LINES_DEF + 1
          LINES(LINENO) = LINES_DEF

          REAC_A='2.1.5a   '
          REAC_B='2.1.8a   '
          REAC_M='2.2.5a   '
          REAC_I2='2.2.14a  '
          REAC_I3='2.2.15a  '
          REAC_N='7.2a     '
          
        END IF
        
      ELSE
        WRITE (IUNOUT,*) 'NO LINE DEFINITION FOUND FOR ENERGY=',ENER
        LINENO = 0
        RETURN
      END IF
      WRITE (IUNOUT,'(A)') LINE_NAME


      IF (LREAD_LINE(LINENO)) THEN
C
C  READ REDUCED POPULATION COEFFICIENT FOR HYDR. ATOMS FROM FILE AMJUEL
C
        IERROR=0
C  NREACI REACTIONS FROM BLOCK
C  + 1 REACTION FOR DENSITY MODELS IN INPUT BLOCK 5
C  + 3 RATIOS OF DENSITIES (= reduced population coefficients)
C  + 6*(NO. OF REACTIONS) DEFINED EARLIER
        IR=NREACI+1+3+(LINES(LINENO)-1)*6
        IF (IR+6.GT.NREAC) THEN
          WRITE (IUNOUT,*) 'FROM SUBROUTINE EIRENE_EMIS_PROFILES: '
          CALL EIRENE_MASPRM('NREAC',5,NREAC,'IR',2,IR,IERROR)
          CALL EIRENE_EXIT_OWN(1)
        ENDIF

        FILNAM='AMJUEL  '
        H123='H.12'
        CRC='OT '

c  default asymptotics
        FP1 = 0._DP
        FP2 = 0._DP
        RC1MIN = -HUGE(1._DP)
        RC1MAX =  HUGE(1._DP)
        RC2MIN = -HUGE(1._DP)
        RC2MAX =  HUGE(1._DP)
        JFEX1MN = 0
        JFEX1MX = 0
        JFEX2MN = 0
        JFEX2MX = 0
C
C  H(n=3)/H(n=1)
        REAC=REAC_A
        CALL EIRENE_SLREAC(IR+1,FILNAM,H123,REAC,CRC,
     .              RC1MIN, RC1MAX, FP1, JFEX1MN, JFEX1MX,
     .              RC2MIN, RC2MAX, FP2, JFEX2MN, JFEX2MX,
     .              '  ',0)
C  H(n=3)/H+
        REAC=REAC_B
        CALL EIRENE_SLREAC(IR+2,FILNAM,H123,REAC,CRC,
     .              RC1MIN, RC1MAX, FP1, JFEX1MN, JFEX1MX,
     .              RC2MIN, RC2MAX, FP2, JFEX2MN, JFEX2MX,
     .              '  ',0)
C  H(n=3)/H2(g)
        REAC=REAC_M
        CALL EIRENE_SLREAC(IR+3,FILNAM,H123,REAC,CRC,
     .              RC1MIN, RC1MAX, FP1, JFEX1MN, JFEX1MX,
     .              RC2MIN, RC2MAX, FP2, JFEX2MN, JFEX2MX,
     .              '  ',0)
C  H(n=3)/H2+(g)
        REAC=REAC_I2
        CALL EIRENE_SLREAC(IR+4,FILNAM,H123,REAC,CRC,
     .              RC1MIN, RC1MAX, FP1, JFEX1MN, JFEX1MX,
     .              RC2MIN, RC2MAX, FP2, JFEX2MN, JFEX2MX,
     .              '  ',0)
C  H(n=3)/H3+
        REAC=REAC_I3
        CALL EIRENE_SLREAC(IR+5,FILNAM,H123,REAC,CRC,
     .              RC1MIN, RC1MAX, FP1, JFEX1MN, JFEX1MX,
     .              RC2MIN, RC2MAX, FP2, JFEX2MN, JFEX2MX,
     .              '  ',0)
C  H(n=3)/H-
        REAC=REAC_N
        CALL EIRENE_SLREAC(IR+6,FILNAM,H123,REAC,CRC,
     .              RC1MIN, RC1MAX, FP1, JFEX1MN, JFEX1MX,
     .              RC2MIN, RC2MAX, FP2, JFEX2MN, JFEX2MX,
     .              '  ',0)

        LREAD_LINE(LINENO) = .FALSE.
C
C  NOW READ RATIO OF DENSITIES (= reduced population coefficients):

C  IF THESE RATIOS ARE USED TO FIND MINORITY DENSITIES (E.G. H-, H2+, H3+), THEN THESE
C  CORRESPOND ("are consistent") TO THE EIRENE H2 DENSITY TALLIES IF:


C  either:
C  THESE SPECIES ARE "NOT FOLLOWED" (NFOL=-1)
C  PLUS IF THE PRODUCTION AND LOSS RATES ARE THE SAME AS THOSE USED TO PRODUCE THE
C  RATIO FITS  (see: AMJUEL database)

C  or:
C  IF THESE SPECIES ARE NOT INCLUDED AT ALL, 
C  BUT THE CORRESPONDING MULTISTEP RATES CONTAINING THEM
C  AS CONDENSED INTERMEDIATE STATES ARE USED
C  FOR THE TRANSPORTED SPECIES (H2) TO WHICH THESE "MINORITES" ARE COUPLED.
C
c.........................................................................

        IF (LINES_DEF == 1) THEN

          IR = NREACI + 1
C
C  FIRST: H-/H2  (COUPLED TO H2(V)
C  H.11 7.0a INCLUDES ELECTRON IMPACT DISS ATTACHMENT ON H2(V), ne=np, Te=Tp, E_H2=E_H-=0.1
C  H.11 7.0b INCLUDES ELECTRON IMPACT DISS ATTACHMENT ON H2(V=0) ONLY
C
          FILNAM='AMJUEL  '
          H123='H.11'
          REAC='7.0a     '
          CRC='OT '
          CALL EIRENE_SLREAC(IR+1,FILNAM,H123,REAC,CRC,
     .              RC1MIN, RC1MAX, FP1, JFEX1MN, JFEX1MX,
     .              RC2MIN, RC2MAX, FP2, JFEX2MN, JFEX2MX,
     .              '  ',0)

C  NEXT: H3+/H2  (COUPLED TO H2(V)
C  H.11 4.0a vs Te, T_H2=T_H2+=0.1 IN H3+ PROD. RATE CONSTANT
C               THE DISTINCTION BETWEEN H2 AND H2(V) IS MADE
C               BY THE ADDITIONAL MULTIPLICATIVE FACTOR RATIO2=H2P/H2 
C
          FILNAM='AMJUEL  '
          H123='H.11'
          REAC='4.0a     '
          CRC='OT '
          CALL EIRENE_SLREAC(IR+2,FILNAM,H123,REAC,CRC,
     .              RC1MIN, RC1MAX, FP1, JFEX1MN, JFEX1MX,
     .              RC2MIN, RC2MAX, FP2, JFEX2MN, JFEX2MX,
     .              '  ',0)

C  NEXT : H2+/H2  (COUPLED TO H2(V))
          FILNAM='AMJUEL  '
          H123='H.12'
          REAC='2.0c     '
          CRC='OT '
c  H2+ from ion conversion alone
C  H.11 2.0c INCLUDES  ION CONVERION (CX) ON H2(V) ne=np,Te=Tp, E_H2=E_H2+=0.1
C  H.11 2.0b INCLUDES  ION CONVERION (CX) ON H2(V=0) ONLY
c  H2+  also from multi-step electron impact ionisation --> explicit ne dependence
C  H.12 2.0c INCLUDES ELECTRON IMPACT IONISATION AND ION CONVERION (CX) ON H2(V)
C  H.12 2.0b INCLUDES ELECTRON IMPACT IONISATION AND ION CONVERION (CX) ON H2(V=0) ONLY
C  H.12 2.0a INCLUDES ELECTRON IMPACT IONISATION ON H2(V=0) ONLY
C
C
CDR: IF CX ON H2(V=1,2...) IS NOT INCLUDED IN A SPECIFIC NEUTRAL TRANSPORT EQUATION
CDR  (SEE INPUT BLOCK 4), THEN IT SHOULD NOT BE INCLUDED HERE EITHER.
C       REAC='2.0b    '
C    IF NEITHER CX on H2(V) nor on H2(V=0) are included, then
C       REAC='2.0a    '
C    IF H2(V=1,2,...) IS NOT IN QSS WITH H2(V=0), THEN RATIOS SHOULD NOT BE USED AT ALL,
C                     OR AT LEAST, MANY SUCH RATIOS, ONE FOR EACH H2(V) METASTABLE STATE.
CDR
          CALL EIRENE_SLREAC(IR+3,FILNAM,H123,REAC,CRC,
     .              RC1MIN, RC1MAX, FP1, JFEX1MN, JFEX1MX,
     .              RC2MIN, RC2MAX, FP2, JFEX2MN, JFEX2MX,
     .              '  ',0)
        ENDIF
      ENDIF
C
C  END OF INITIALIZATION
C

      END SUBROUTINE EIRENE_PREPARE_LINE 

      END SUBROUTINE EIRENE_EMIS_PROFILES
