      TXTTAL(IAD4,NTALA) =TXTTAL(IAD1,NTALA)
      TXTSPC(IAD4,NTALA) ='DIAT.MOL.IONS       '
      TXTUNT(IAD4,NTALA) ='PHOTONS/S/CM**3         '

